def P(t, s=base): return Paragraph(t, s)
def bullets(items):
    return ListFlowable([ListItem(P(i), leftIndent=14) for i in items], bulletType='bullet', start='•', leftIndent=14, bulletFontName='DV')
def steps(items):
    return ListFlowable([ListItem(P(i), leftIndent=16) for i in items], bulletType='1', leftIndent=16, bulletFontName='DVB')
def table(rows, widths):
    data = [[P(c, cellb if r == 0 else cell) for c in row] for r, row in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,0), colors.HexColor('#ece7da')),
        ('GRID', (0,0), (-1,-1), 0.4, colors.HexColor('#cfc8b6')), ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ('TOPPADDING', (0,0), (-1,-1), 4), ('BOTTOMPADDING', (0,0), (-1,-1), 4)]))
    return t

